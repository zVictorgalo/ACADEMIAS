-- Tabelas exclusivas do Pulso. Não altera as tabelas auth.users do Supabase.
-- O login próprio preserva PINs de 4 dígitos e hashes existentes do Django.
create table public.pulso_users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  name text not null,
  email text not null,
  password_hash text not null,
  is_admin boolean not null default false,
  is_active boolean not null default true,
  auth_version integer not null default 0,
  created_at timestamptz not null default now()
);
create table public.pulso_members (
  id bigint generated by default as identity primary key,
  user_id bigint not null unique references public.pulso_users(id) on delete cascade,
  role text not null default 'student' check (role in ('student','employee')),
  status text not null default 'pending' check (status in ('pending','approved','blocked','rejected')),
  block_reason text not null default '' check (block_reason in ('','unpaid','overdue','expired','requested','other')),
  block_notes text not null default '',
  created_at timestamptz not null default now()
);
create table public.pulso_entries (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.pulso_members(id) on delete cascade,
  created_at timestamptz not null default now(),
  day date,
  unique(member_id,day)
);
create table public.pulso_events (
  id bigint generated by default as identity primary key,
  member_id bigint not null references public.pulso_members(id) on delete cascade,
  actor_id bigint not null references public.pulso_users(id),
  status text not null,
  reason text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);
create table public.pulso_sessions (
  token_hash text primary key,
  user_id bigint not null references public.pulso_users(id) on delete cascade,
  auth_version integer not null,
  expires_at timestamptz not null
);
create table public.pulso_attempts (
  key text primary key,
  failures integer not null default 0,
  window_started timestamptz not null default now()
);
create table public.pulso_terminals (
  id uuid primary key default gen_random_uuid(),
  owner_id bigint not null references public.pulso_users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table public.pulso_tickets (
  id uuid primary key default gen_random_uuid(),
  terminal_id uuid not null references public.pulso_terminals(id) on delete cascade,
  expires_at timestamptz not null default now() + interval '3 minutes',
  created_at timestamptz not null default now(),
  consumed_at timestamptz,
  decision text check(decision in ('granted','denied')),
  member_id bigint references public.pulso_members(id) on delete set null
);
create index pulso_entries_member_time on public.pulso_entries(member_id,created_at desc);
create index pulso_tickets_terminal_time on public.pulso_tickets(terminal_id,created_at desc);
create index pulso_members_status on public.pulso_members(status);
create index pulso_sessions_expiration on public.pulso_sessions(expires_at);

-- A API do banco não é aberta ao navegador. Apenas a Edge Function usa service_role.
do $$ declare t text; begin
  foreach t in array array['pulso_users','pulso_members','pulso_entries','pulso_events','pulso_sessions','pulso_attempts','pulso_terminals','pulso_tickets'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on public.%I from anon, authenticated',t);
    execute format('grant all on public.%I to service_role',t);
  end loop;
end $$;

-- Cada chamada é uma transação PostgreSQL. Os registros de entrada e de auditoria
-- são gravados junto da alteração de status, sem depender de várias chamadas HTTP.
create function public.pulso_api(op text, p jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  u public.pulso_users%rowtype;
  m public.pulso_members%rowtype;
  t public.pulso_tickets%rowtype;
  terminal public.pulso_terminals%rowtype;
  attempts public.pulso_attempts%rowtype;
  rows jsonb;
  events jsonb;
  uid bigint;
  today date := (now() at time zone 'America/Sao_Paulo')::date;
  allowed boolean;
  target_status text;
begin
  if op = 'health' then return jsonb_build_object('status','ok'); end if;
  if op = 'rate' then
    insert into public.pulso_attempts(key) values(p->>'key') on conflict do nothing;
    select * into attempts from public.pulso_attempts where key=p->>'key' for update;
    if attempts.window_started <= now()-make_interval(secs=>(p->>'seconds')::integer) then
      update public.pulso_attempts set failures=0,window_started=now() where key=p->>'key';
      attempts.failures:=0;
    end if;
    allowed:=attempts.failures < (p->>'limit')::integer;
    if allowed then update public.pulso_attempts set failures=failures+1 where key=p->>'key'; end if;
    return jsonb_build_object('allowed',allowed);
  elsif op = 'rate_clear' then
    delete from public.pulso_attempts where key=p->>'key'; return '{}'::jsonb;
  elsif op = 'login_lookup' then
    if (p->>'identifier') ~ '^[0-9]{1,18}$' then
      select a.* into u from public.pulso_users a join public.pulso_members b on b.user_id=a.id
        where b.id=(p->>'identifier')::bigint;
    else
      select * into u from public.pulso_users where username=p->>'identifier';
    end if;
    if u.id is null or not u.is_active then return 'null'::jsonb; end if;
    return to_jsonb(u);
  elsif op = 'session_create' then
    insert into public.pulso_sessions(token_hash,user_id,auth_version,expires_at)
      select p->>'token_hash',id,auth_version,now()+interval '8 hours' from public.pulso_users
      where id=(p->>'user_id')::bigint and is_active;
    return '{}'::jsonb;
  elsif op = 'session_delete' then
    delete from public.pulso_sessions where token_hash=p->>'token_hash'; return '{}'::jsonb;
  elsif op = 'session_get' then
    select a.* into u from public.pulso_users a join public.pulso_sessions s on s.user_id=a.id
      where s.token_hash=p->>'token_hash' and s.expires_at>now() and s.auth_version=a.auth_version and a.is_active;
    if u.id is null then return 'null'::jsonb; end if;
    return to_jsonb(u)-'password_hash';
  end if;

  if p ? 'actor_id' then
    select * into u from public.pulso_users where id=(p->>'actor_id')::bigint and is_active;
  end if;
  if op in ('management','member_status','pin_reset','terminal_create','terminal_state')
      or (op='signup' and p ? 'actor_id') then
    if u.id is null or not u.is_admin then raise exception 'Acesso restrito ao administrador.'; end if;
  end if;

  if op = 'signup' then
    insert into public.pulso_users(username,name,email,password_hash)
      values('member_'||gen_random_uuid()::text,p->>'name',p->>'email',p->>'password_hash') returning id into uid;
    insert into public.pulso_members(user_id,role,status)
      values(uid,case when u.is_admin then coalesce(p->>'role','student') else 'student' end,
        case when u.is_admin then 'approved' else 'pending' end) returning * into m;
    if u.is_admin then
      insert into public.pulso_events(member_id,actor_id,status) values(m.id,u.id,m.status);
    end if;
    return jsonb_build_object('id',m.id,'access_id',lpad(m.id::text,greatest(6,length(m.id::text)),'0'),'name',p->>'name','status',m.status);
  elsif op = 'me' then
    if u.id is null then raise exception 'Entre na sua conta.'; end if;
    select * into m from public.pulso_members where user_id=u.id;
    select coalesce(jsonb_agg(to_jsonb(e) order by e.created_at desc),'[]'::jsonb) into rows
      from public.pulso_entries e where member_id=m.id;
    return jsonb_build_object('user',to_jsonb(u)-'password_hash', 'member',case when m.id is null then 'null'::jsonb else to_jsonb(m)-'block_notes' end,'entries',rows);
  elsif op = 'management' then
    select coalesce(jsonb_agg(x order by x->>'created_at' desc),'[]'::jsonb) into rows from (
      select to_jsonb(b)||jsonb_build_object('name',a.name,'email',a.email) as x
      from public.pulso_members b join public.pulso_users a on a.id=b.user_id
      where (coalesce(p->>'status','')='' or b.status=p->>'status')
        and (coalesce(p->>'reason','')='' or (b.status='blocked' and b.block_reason=p->>'reason'))
        and (coalesce(p->>'q','')='' or a.name ilike '%'||(p->>'q')||'%'
          or a.email ilike '%'||(p->>'q')||'%' or ltrim(p->>'q','0')=b.id::text)
    ) s;
    select coalesce(jsonb_agg(to_jsonb(s) order by s.created_at desc),'[]'::jsonb) into events from (
      select e.*,a.name as member_name,b.name as actor_name from public.pulso_events e
      join public.pulso_members m on m.id=e.member_id join public.pulso_users a on a.id=m.user_id
      join public.pulso_users b on b.id=e.actor_id order by e.created_at desc limit 20
    ) s;
    return jsonb_build_object('members',rows,'events',events,'stats',jsonb_build_object(
      'total',(select count(*) from public.pulso_members),
      'pending',(select count(*) from public.pulso_members where status='pending'),
      'approved',(select count(*) from public.pulso_members where status='approved'),
      'blocked',(select count(*) from public.pulso_members where status='blocked'),
      'today',(select count(*) from public.pulso_entries where day=today)));
  elsif op = 'member_status' then
    target_status:=p->>'status';
    if target_status not in ('approved','blocked','rejected') then raise exception 'Situação inválida.'; end if;
    if target_status='blocked' and coalesce(p->>'reason','') not in ('unpaid','overdue','expired','requested','other') then
      raise exception 'Selecione o motivo do bloqueio.';
    end if;
    update public.pulso_members set status=target_status,
      block_reason=case when target_status='blocked' then p->>'reason' else '' end,
      block_notes=case when target_status='blocked' then left(coalesce(p->>'notes',''),500) else '' end
      where id=(p->>'member_id')::bigint returning * into m;
    if m.id is null then raise exception 'Cadastro não encontrado.'; end if;
    insert into public.pulso_events(member_id,actor_id,status,reason,notes) values(m.id,u.id,m.status,m.block_reason,m.block_notes);
    return jsonb_build_object('ok',true);
  elsif op = 'pin_reset' then
    select * into m from public.pulso_members where id=(p->>'member_id')::bigint;
    if m.id is null then raise exception 'Cadastro não encontrado.'; end if;
    update public.pulso_users set password_hash=p->>'password_hash',auth_version=auth_version+1 where id=m.user_id;
    delete from public.pulso_sessions where user_id=m.user_id;
    return jsonb_build_object('ok',true);
  elsif op = 'terminal_create' then
    insert into public.pulso_terminals(owner_id) values(u.id) returning * into terminal;
    return to_jsonb(terminal);
  elsif op = 'terminal_state' then
    select * into terminal from public.pulso_terminals where id=(p->>'terminal_id')::uuid and owner_id=u.id for update;
    if terminal.id is null then raise exception 'Painel não encontrado.'; end if;
    select * into t from public.pulso_tickets where terminal_id=terminal.id and consumed_at is null and expires_at>now() order by created_at desc limit 1;
    if t.id is null then insert into public.pulso_tickets(terminal_id) values(terminal.id) returning * into t; end if;
    return jsonb_build_object('ticket_id',t.id,'expires_at',t.expires_at,'decision',coalesce((
      select decision from public.pulso_tickets where terminal_id=terminal.id and consumed_at>now()-interval '8 seconds'
      order by consumed_at desc limit 1),''));
  elsif op = 'ticket_info' then
    select * into t from public.pulso_tickets where id=(p->>'ticket_id')::uuid;
    if t.id is null then return jsonb_build_object('expired',true); end if;
    if t.consumed_at is not null then
      if exists(select 1 from public.pulso_members where id=t.member_id and user_id=u.id) then
        return jsonb_build_object('decision',t.decision);
      end if;
      return jsonb_build_object('expired',true);
    end if;
    return jsonb_build_object('expired',t.expires_at<=now());
  elsif op = 'ticket_consume' then
    if u.id is null then raise exception 'Entre com seu ID e PIN.'; end if;
    select * into m from public.pulso_members where user_id=u.id for share;
    if m.id is null then raise exception 'Use uma conta de aluno ou funcionário.'; end if;
    select * into t from public.pulso_tickets where id=(p->>'ticket_id')::uuid for update;
    if t.id is null then return jsonb_build_object('expired',true); end if;
    if t.consumed_at is not null then
      if t.member_id=m.id then return jsonb_build_object('decision',t.decision); end if;
      return jsonb_build_object('expired',true);
    end if;
    if t.expires_at<=now() then return jsonb_build_object('expired',true); end if;
    t.decision:=case when m.status='approved' then 'granted' else 'denied' end;
    update public.pulso_tickets set consumed_at=now(),member_id=m.id,decision=t.decision where id=t.id;
    if t.decision='granted' then
      insert into public.pulso_entries(member_id,day) values(m.id,today) on conflict(member_id,day) do nothing;
    end if;
    return jsonb_build_object('decision',t.decision);
  end if;
  raise exception 'Operação inválida.';
end $$;
revoke all on function public.pulso_api(text,jsonb) from public,anon,authenticated;
grant execute on function public.pulso_api(text,jsonb) to service_role;
